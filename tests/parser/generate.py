"""Generates the self-hosted parser's (questlang/syntax/parser's) golden tests from the bootstrap parser.

Each input tests/parser/NAME.quest holds cases, separated by lines that are just "(* ---- *)". It gives a golden test,
tests/source/questlang/parser_NAME.quest, which parses each case with the self-hosted parser and prints its AST with
astprint.dump, or its syntax error; tests/golden/run/questlang/parser_NAME.out holds what the bootstrap's parser and
ast_dump give for each case, which the test must print.

    python tests/parser/generate.py

Run it after changing an input; the tests run as part of the test suite.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT_DIR / "bootstrap" / "python"))

import quest.syntax.ast as A  # noqa: E402
from quest.syntax.grammar import parse_quest_program  # noqa: E402
from quest.syntax.parser import ParserError  # noqa: E402
from quest.syntax.tokenizer import Tokenizer  # noqa: E402

HERE = Path(__file__).resolve().parent
TEST_DIR = ROOT_DIR / "tests" / "source" / "questlang"
GOLDEN_DIR = ROOT_DIR / "tests" / "golden" / "run" / "questlang"
SEPARATOR = "(* ---- *)"


def qstr(s: str) -> str:
    """s as a Quest string literal."""
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append(f"\\{o:03d}")
    out.append('"')
    return "".join(out)


def cases(source: Path) -> list[str]:
    parts, current = [], []
    for line in source.read_text().splitlines(keepends=True):
        if line.strip() == SEPARATOR:
            parts.append("".join(current))
            current = []
        else:
            current.append(line)
    parts.append("".join(current))
    return parts


def expected(name: str, text: str) -> str:
    """What the bootstrap gives for a case: its AST, or its syntax error."""
    tok = Tokenizer(text, name)
    try:
        return A.ast_dump(parse_quest_program(tok.tokenize_all(), tok.source_map))
    except ParserError as e:
        return f"error at {e.offset}-{e.offset + e.length}: {e.message}"


PRELUDE = """import
    questlang/common/location : questlang/common/Location
    questlang/common/diagnostics : questlang/common/Diagnostics
    questlang/common/diagbag : questlang/common/DiagBag
    questlang/syntax/tokenizer : questlang/syntax/Tokenizer
    questlang/syntax/parser : questlang/syntax/Parser
    questlang/syntax/astprint : questlang/syntax/AstPrint
    writer : Writer
    conv : Conv
;

let emit(s: String): Ok = begin writer.putString(writer.output s) writer.putString(writer.output "\\n") end;

(* Prints a case's AST, or its syntax error *)
let parse(name: String text: String): Ok =
    begin
        let sm = location.newSourceMap(name text)
        let bag = diagbag.new()
        let toks = tokenizer.tokenizeAll(tokenizer.new(sm bag))
        try
            emit(astprint.dump(parser.parseProgram(toks sm bag)))
        when diagbag.fatalError with d then
            let sp = diagnostics.span(d)
            emit("error at " <> conv.int(sp.startOffset) <> "-" <> conv.int(sp.endOffset) <> ": " <> diagnostics.message(d))
        end
    end;

"""


def generate_tests() -> None:
    for source in sorted(HERE.glob("*.quest")):
        name = source.name
        header = (
            f"(* Generated by tests/parser/generate.py from tests/parser/{name}; do not edit. It parses each case with\n"
            "   the self-hosted parser and prints its AST, or its syntax error, as the bootstrap's parser and ast_dump\n"
            "   give them. *)\n"
            "(* @skip-phase: tokenize, parse, typecheck, ir_core *)\n"
            "(* @timeout: 300.0 *)\n\n"
        )
        texts = cases(source)
        calls = "".join(f"parse({qstr(name)} {qstr(text)});\n" for text in texts)
        program = TEST_DIR / f"parser_{source.stem}.quest"
        golden = GOLDEN_DIR / f"parser_{source.stem}.out"
        program.write_text(header + PRELUDE + calls)
        golden.write_text("".join(expected(name, text) + "\n" for text in texts))
        print(f"wrote {program.relative_to(ROOT_DIR)} and {golden.relative_to(ROOT_DIR)}")


if __name__ == "__main__":
    generate_tests()
