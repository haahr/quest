"""The ABI corpus: generated interface artifacts that pin the artifact contract
(docs/build-process.md §5.2.3).

The corpus is generated from a frozen snapshot of the interfaces in lib/ and
questlang/ (tests/abi/inputs), so that it changes only when the compiler's
output for the same input changes, not when the library evolves. It holds each
interface's generated .qi file and C header, normalized so that only
contract-relevant content remains (no producer stamp, no comments), plus a
digest of the runtime interface (runtime/quest_runtime.h) and the ABI version
the corpus was generated with. tests/python/test_abi_corpus.py regenerates it
and fails if it changed while ABI_VERSION did not.

Each compiler has its own corpus, since each compiler's artifacts are its own
(docs/testing.md section 2.8): tests/abi/corpus is the bootstrap's, and
tests/abi/corpus-self-hosted the self-hosted compiler's, which run_tests.py
--self-hosted checks. The two share ABI_VERSION, which changes when either does.

    # After bumping ABI_VERSION, regenerate the bootstrap's corpus:
    python tests/abi/corpus.py --update
    # Re-snapshot lib/ and questlang/ interfaces, then regenerate it:
    python tests/abi/corpus.py --refresh-inputs
    # Generate the self-hosted compiler's with its driver, and compare:
    python tests/abi/corpus.py --compiler PATH
    # ... or regenerate it:
    python tests/abi/corpus.py --update --compiler PATH
"""

from __future__ import annotations

import hashlib
import json
import re
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT_DIR / "bootstrap" / "python"))

from quest.config.abi import ABI_VERSION  # noqa: E402
from quest.codegen.c.headers import compile_interface_with_header  # noqa: E402

ABI_DIR = Path(__file__).resolve().parent
CORPUS_DIR = ABI_DIR / "corpus"
SELF_HOSTED_CORPUS_DIR = ABI_DIR / "corpus-self-hosted"
INPUTS_DIR = ABI_DIR / "inputs"
# Snapshot layout mirrors the search roots: inputs/lib/... (like lib/) and
# inputs/questlang/... (under the project).
SNAPSHOT_SOURCES = ((ROOT_DIR / "lib", INPUTS_DIR / "lib"), (ROOT_DIR / "questlang", INPUTS_DIR / "questlang"))
RUNTIME_HEADER = ROOT_DIR / "runtime" / "quest_runtime.h"


def _normalize_qi(text: str) -> str:
    data = json.loads(text)
    value = data.get("value", {})
    value.pop("producer", None)
    value.pop("abi", None)
    # The recorded source is an absolute path; keep only its location within the
    # inputs.
    if value.get("source"):
        value["source"] = Path(value["source"]).relative_to(INPUTS_DIR.resolve()).as_posix()
    # So are the directories and sources of the interfaces it depends on.
    for dep in value.get("deps", []):
        for key in ("dir", "source"):
            if dep.get(key):
                dep[key] = Path(dep[key]).relative_to(INPUTS_DIR.resolve()).as_posix()
    return json.dumps(data, indent=2, sort_keys=True) + "\n"


def _normalize_header(text: str) -> str:
    without_comments = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    lines = [line.rstrip() for line in without_comments.splitlines()]
    return "\n".join(line for line in lines if line) + "\n"


def generate(compiler: str | None = None) -> dict[str, str]:
    """Returns the corpus as {relative path: content}, generated by the
    bootstrap, or by the compiler at path compiler (as `compiler -c -I ...
    --build-dir ... FILE` compiles an interface file)."""
    corpus: dict[str, str] = {}
    with tempfile.TemporaryDirectory() as tmp:
        build_dir = Path(tmp)
        include_paths = [INPUTS_DIR / "lib", INPUTS_DIR]
        for src in sorted(INPUTS_DIR.rglob("*.int.quest")):
            if compiler is None:
                compile_interface_with_header(src, include_paths=include_paths, build_dir=build_dir)
                continue
            command = [compiler, "-c", *(arg for path in include_paths for arg in ("-I", str(path))),
                       "--build-dir", str(build_dir), str(src)]
            # The project directory, whose lib/ the self-hosted driver reads
            # the standard library from
            environment = {**os.environ, "QUEST_HOME": str(ROOT_DIR)}
            process = subprocess.run(command, capture_output=True, text=True, env=environment)
            if process.returncode != 0:
                raise RuntimeError(f"{compiler} failed on {src}:\n{process.stderr}")
        for artifact in sorted(build_dir.rglob("*")):
            if not artifact.is_file():
                continue
            rel = artifact.relative_to(build_dir).as_posix()
            text = artifact.read_text(encoding="utf-8")
            if artifact.suffix == ".qi":
                corpus[rel] = _normalize_qi(text)
            elif artifact.suffix == ".h":
                corpus[rel] = _normalize_header(text)
    corpus["quest_runtime.h.sha256"] = hashlib.sha256(RUNTIME_HEADER.read_bytes()).hexdigest() + "\n"
    corpus["ABI_VERSION"] = f"{ABI_VERSION}\n"
    return corpus


def read_checked_in(corpus_dir: Path = CORPUS_DIR) -> dict[str, str]:
    if not corpus_dir.is_dir():
        return {}
    return {
        p.relative_to(corpus_dir).as_posix(): p.read_text(encoding="utf-8")
        for p in sorted(corpus_dir.rglob("*"))
        if p.is_file()
    }


def refresh_inputs() -> None:
    if INPUTS_DIR.exists():
        shutil.rmtree(INPUTS_DIR)
    for source_root, snapshot_root in SNAPSHOT_SOURCES:
        for src in sorted(source_root.rglob("*.int.quest")):
            dest = snapshot_root / src.relative_to(source_root)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, dest)


def update(compiler: str | None = None) -> Path:
    """Regenerates the bootstrap's corpus, or with compiler the self-hosted
    compiler's; returns its directory."""
    corpus_dir = CORPUS_DIR if compiler is None else SELF_HOSTED_CORPUS_DIR
    if corpus_dir.exists():
        shutil.rmtree(corpus_dir)
    for rel, content in generate(compiler).items():
        path = corpus_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return corpus_dir


def compare(compiler: str) -> int:
    """Generates the corpus with compiler, the self-hosted driver, and reports
    where it differs from the self-hosted compiler's checked-in one; returns the
    number of differing files."""
    expected = read_checked_in(SELF_HOSTED_CORPUS_DIR)
    actual = generate(compiler)
    paths = sorted(set(expected) | set(actual))
    differing = 0
    for rel in paths:
        if expected.get(rel) != actual.get(rel):
            differing += 1
            print(f"differs: {rel}")
    print(f"{len(paths) - differing} of {len(paths)} corpus files agree")
    return differing


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--compiler":
        sys.exit(1 if compare(sys.argv[2]) else 0)
    if len(sys.argv) == 4 and sys.argv[1:3] == ["--update", "--compiler"]:
        written = update(sys.argv[3])
        print(f"Wrote ABI corpus for ABI version {ABI_VERSION} to {written}")
    elif sys.argv[1:] in (["--update"], ["--refresh-inputs"]):
        if sys.argv[1] == "--refresh-inputs":
            refresh_inputs()
            print(f"Snapshotted interfaces into {INPUTS_DIR}")
        written = update()
        print(f"Wrote ABI corpus for ABI version {ABI_VERSION} to {written}")
    else:
        print(__doc__)
        sys.exit(2)
